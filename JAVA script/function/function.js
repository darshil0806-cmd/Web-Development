function greet(name) {
  console.log("Hello, " + name + "!");
}
greet("Alice"); // Output: Hello, Alice!

function add(a, b) {
  return a + b;
}

let result = add(5, 10);
console.log(result); // Output: 15

const square = (x) => {
  return x * x;
};

console.log(square(5)); // Output: 25